from __future__ import annotations

import os
from pathlib import Path


def _write_openai_config(config_path: Path, script_path: str) -> None:
    # Generic OpenAI provider: the real api.openai.com by default, or any
    # OpenAI-compatible endpoint when OPENAI_BASE_URL is set. The API key is read
    # from the OPENAI_API_KEY environment variable and is never stored here.
    model = os.environ["OPENAI_MODEL"]
    base_url = os.environ.get("OPENAI_BASE_URL", "").strip()
    max_input_tokens = int(os.environ.get("OPENAI_MAX_INPUT_TOKENS", "128000"))
    base_url_line = (
        f'\n[models.providers.openai.params]\nbase_url = "{base_url}"\n'
        if base_url
        else ""
    )

    config_path.write_text(
        f"""# Generated by {script_path}.
# Secrets are intentionally not stored here; the API key is read from the
# OPENAI_API_KEY environment variable. Set OPENAI_BASE_URL to target an
# OpenAI-compatible endpoint instead of the real OpenAI API.

[update]
check = false
auto_update = false

[warnings]
suppress = ["tavily"]

[models]
default = "openai:{model}"

[models.providers.openai]
models = ["{model}"]
api_key_env = "OPENAI_API_KEY"
{base_url_line}
[models.providers.openai.profile]
tool_calling = true
max_input_tokens = {max_input_tokens}
""",
        encoding="utf-8",
    )


def _write_vllm_config(config_path: Path, script_path: str) -> None:
    # Local vLLM (NVIDIA / DGX) OpenAI-compatible server. dcode reaches it
    # through the generic `openai` provider with base_url pointed at VLLM_BASE_URL.
    # The API key is read from VLLM_API_KEY (often a dummy local value).
    model = os.environ["VLLM_MODEL"]
    base_url = os.environ.get("VLLM_BASE_URL", "http://127.0.0.1:8000/v1")
    max_input_tokens = int(os.environ.get("VLLM_MAX_INPUT_TOKENS", "131072"))

    config_path.write_text(
        f"""# Generated by {script_path}.
# Local vLLM is OpenAI-compatible; it is wired through the `openai` provider
# with base_url pointed at the vLLM server. The API key is read from the
# VLLM_API_KEY environment variable and is intentionally not stored here.

[update]
check = false
auto_update = false

[warnings]
suppress = ["tavily"]

[models]
default = "openai:{model}"

[models.providers.openai]
models = ["{model}"]
api_key_env = "VLLM_API_KEY"

# vLLM implements chat-completions; force off Responses API so ChatOpenAI
# does not POST /v1/responses (which most vLLM builds 404).
[models.providers.openai.params]
base_url = "{base_url}"
use_responses_api = false

[models.providers.openai.profile]
tool_calling = true
max_input_tokens = {max_input_tokens}
""",
        encoding="utf-8",
    )


def main() -> None:
    config_dir = Path(os.environ["CONFIG_DIR"])
    config_path = Path(os.environ["CONFIG_PATH"])
    script_path = os.environ["SCRIPT_PATH"]
    provider = os.environ.get("DEEPAGENTS_MODEL_PROVIDER", "vllm").strip().lower()
    # Shared Ralph upgrade prompts still say `omlx`; on this DGX fork that is
    # the local OpenAI-compatible vLLM endpoint.
    if provider == "omlx":
        provider = "vllm"

    config_dir.mkdir(parents=True, exist_ok=True)
    if provider == "vllm":
        _write_vllm_config(config_path, script_path)
    elif provider == "openai":
        _write_openai_config(config_path, script_path)
    else:
        raise SystemExit(
            f"Unsupported DEEPAGENTS_MODEL_PROVIDER={provider!r}. Expected vllm, omlx, or openai."
        )


if __name__ == "__main__":
    main()
